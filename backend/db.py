class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return dict.__getitem__(self, key)


class _Result:
    def __init__(self, rows: list[Row], lastrowid):
        self._rows = rows
        self._index = 0
        self.lastrowid = lastrowid

    def fetchone(self):
        if self._index >= len(self._rows):
            return None
        row = self._rows[self._index]
        self._index += 1
        return row

    def fetchall(self):
        rows = self._rows[self._index:]
        self._index = len(self._rows)
        return rows


class Connection:
    """PostgreSQL connection with the small SQLite-style surface the desk already uses."""

    def __init__(self, raw):
        self._raw = raw

    def execute(self, sql: str, params=None):
        sql = _placeholders(sql)
        sql, returning = _with_returning(sql)
        with self._raw.cursor() as cur:
            cur.execute(sql, params or ())
            rows = []
            lastrowid = None
            if cur.description is not None:
                rows = [Row(item) for item in cur.fetchall()]
            if returning and rows:
                lastrowid = rows[0].get("id")
        return _Result(rows, lastrowid)

    def executemany(self, sql: str, seq) -> _Result:
        rows = list(seq)
        if not rows:
            return _Result([], None)
        sql = _placeholders(sql)
        with self._raw.cursor() as cur:
            cur.executemany(sql, rows)
        return _Result([], None)

    def executescript(self, script: str) -> None:
        for statement in _split_sql(script):
            self.execute(statement)

    def commit(self) -> None:
        self._raw.commit()

    def rollback(self) -> None:
        self._raw.rollback()

    def close(self) -> None:
        self._raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                self.rollback()
            else:
                self.commit()
        finally:
            self.close()
        return False


def _load_env() -> None:
    path = ROOT / ".env"
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def _database_url() -> str:
    _load_env()
    url = os.environ.get("DATABASE_URL", "").strip()
    if url:
        return url
    raise RuntimeError(
        "Set DATABASE_URL in .env to the PostgreSQL database Whatsapp Tutor."
    )


def _placeholders(sql: str) -> str:
    out = []
    in_string = False
    index = 0
    while index < len(sql):
        char = sql[index]
        if char == "'":
            if in_string and index + 1 < len(sql) and sql[index + 1] == "'":
                out.append("''")
                index += 2
                continue
            in_string = not in_string
            out.append(char)
        elif char == "?" and not in_string:
            out.append("%s")
        else:
            out.append(char)
        index += 1
    sql = "".join(out)
    return re.sub(
        r"datetime\(\s*'now'\s*\)",
        "to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')",
        sql,
        flags=re.I,
    )


def _with_returning(sql: str) -> tuple[str, bool]:
    match = re.match(r"\s*INSERT\s+INTO\s+([A-Za-z_][\w]*)", sql, re.I)
    if not match or match.group(1).lower() not in _IDENTITY_TABLES:
        return sql, False
    if re.search(r"\bRETURNING\b", sql, re.I):
        return sql, True
    return sql.rstrip().rstrip(";") + " RETURNING id", True


def _split_sql(script: str) -> list[str]:
    parts = []
    current = []
    in_string = False
    index = 0
    while index < len(script):
        char = script[index]
        if char == "'":
            if in_string and index + 1 < len(script) and script[index + 1] == "'":
                current.append("''")
                index += 2
                continue
            in_string = not in_string
        if char == ";" and not in_string:
            statement = "".join(current).strip()
            if statement:
                parts.append(statement)
            current = []
        else:
            current.append(char)
        index += 1
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def connect() -> Connection:
    DATA.mkdir(parents=True, exist_ok=True)
    UPLOADS.mkdir(parents=True, exist_ok=True)
    raw = psycopg.connect(_database_url(), row_factory=dict_row, connect_timeout=8)
    return Connection(raw)


def now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def ago(days: int, hours: int = 9) -> str:
    return (datetime.now() - timedelta(days=days, hours=hours)).strftime("%Y-%m-%d %H:%M:%S")


def init_db() -> None:
    with connect() as conn:
        conn.executescript(SCHEMA)
        _migrate_people(conn)
        _import_sqlite(conn)
        count = conn.execute("SELECT COUNT(*) AS n FROM people").fetchone()["n"]
        if count == 0:
            _seed(conn)
        _ensure_accounts(conn)
        conn.commit()


def _columns(conn, table: str) -> set[str]:
    rows = conn.execute(
        """
        SELECT column_name AS name
          FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = ?
        """,
        (table,),
    ).fetchall()
    return {row["name"] for row in rows}


def _migrate_people(conn) -> None:
    columns = _columns(conn, "people")
    if "username" not in columns:
        conn.execute("ALTER TABLE people ADD COLUMN username TEXT")
    if "password_hash" not in columns:
        conn.execute("ALTER TABLE people ADD COLUMN password_hash TEXT")
    if "active" not in columns:
        conn.execute("ALTER TABLE people ADD COLUMN active INTEGER NOT NULL DEFAULT 1")
    if "created_at" not in columns:
        conn.execute("ALTER TABLE people ADD COLUMN created_at TEXT")
    if "phone" not in columns:
        conn.execute("ALTER TABLE people ADD COLUMN phone TEXT")
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS sessions (
            token TEXT PRIMARY KEY,
            person_id TEXT NOT NULL,
            created_at TEXT NOT NULL
        )
        """
    )
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_people_username ON people(username)")
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_people_phone ON people(phone) WHERE phone IS NOT NULL AND phone <> ''"
    )


def _import_sqlite(conn) -> None:
    """Copy the previous local file once, when PostgreSQL has no accounts yet."""
    if not DB_PATH.exists():
        return
    existing = conn.execute("SELECT COUNT(*) AS n FROM people").fetchone()["n"]
    if existing:
        return
    source = sqlite3.connect(DB_PATH)
    source.row_factory = sqlite3.Row
    try:
        tables = {
            row["name"]
            for row in source.execute("SELECT name FROM sqlite_master WHERE type = 'table'")
        }
        order = [
            "people",
            "sessions",
            "documents",
            "chunks",
            "questions",
            "practice_items",
            "activity",
            "exam_results",
            "settings",
            "chat_messages",
            "chat_state",
            "whatsapp_seen",
        ]
        for table in order:
            if table not in tables:
                continue
            rows = source.execute(f"SELECT * FROM {table}").fetchall()
            if not rows:
                continue
            columns = list(rows[0].keys())
            placeholders = ", ".join("?" for _ in columns)
            names = ", ".join(columns)
            conn.executemany(
                f"INSERT INTO {table} ({names}) VALUES ({placeholders})",
                [tuple(row[column] for column in columns) for row in rows],
            )
        for table in _IDENTITY_TABLES:
            conn.execute(
                f"""
                SELECT setval(
                    pg_get_serial_sequence('{table}', 'id'),
                    GREATEST(COALESCE((SELECT MAX(id) FROM {table}), 1), 1),
                    (SELECT MAX(id) IS NOT NULL FROM {table})
                )
                """
            )
    finally:
        source.close()


def hash_password(password: str) -> str:
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 120_000)
    return f"{salt}${digest.hex()}"


def verify_password(password: str, stored: str | None) -> bool:
    if not stored or "$" not in stored:
        return False
    salt, digest = stored.split("$", 1)
    check = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 120_000).hex()
    return secrets.compare_digest(check, digest)


def public_person(row: dict) -> dict:
    data = dict(row)
    data.pop("password_hash", None)
    return data


def normalise_phone(value: str) -> str:
    digits = re.sub(r"\D", "", value or "")
    if digits.startswith("00"):
        digits = digits[2:]
    if len(digits) == 10 and digits.startswith("0"):
        digits = "27" + digits[1:]
    if not re.fullmatch(r"[1-9]\d{9,14}", digits):
        raise ValueError("Enter the WhatsApp number with the country code, for example 27821234567.")
    return digits


